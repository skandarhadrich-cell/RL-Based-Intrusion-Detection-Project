"""Coverage-ablation evaluation: does adding the missing concepts help detection?

Scores the **baseline** mask-free agents (no PortScan / ~no Infilteration in
training) and the **coverage** agents (retrained on the augmented corpus) on the
same two unseen test sets carved by ``coverage_split.py``:

  * PortScan test (2017)     - Suspicious class, label ``PortScan``
  * Infiltration test (2018) - Compromised class, label ``Infilteration``

Detection is read from the agent's own greedy action (mask-free), exactly as in
``maskfree_detect.py``; no mask, no label leakage.  The headline number is the
attack-label **recall** (how much of the previously-unseen family is now caught)
read together with the benign false-alarm rate.

Writes:
  * ``data/processed/coverage_ablation_report.md``
  * ``data/processed/coverage_ablation_confusion.png``

Run:  PYTHONPATH=src python -m rl_ids.coverage_eval
"""
from __future__ import annotations

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from rl_ids import config as C
from rl_ids.dqn import DoubleDQNAgent
from rl_ids.maskfree_detect import CONDITIONS, DRAWS, evaluate
from rl_ids.metrics import macro_average

BENIGN = "Normal"
BENIGN_CAP = 30_000
SEED = 0

# (test parquet, severity bucket of the attack, ground-truth label string)
TESTS: dict[str, tuple] = {
    "PortScan test (2017)": (C.COVERAGE_TEST_PORTSCAN_PARQUET, "Suspicious", "PortScan"),
    "Infiltration test (2018)": (C.COVERAGE_TEST_INFILTRATION_PARQUET,
                                 "Compromised", "Infilteration"),
}

MODELS: list[tuple[str, str, str]] = [
    # (display name, model path, group)
    ("baseline mask-free DQN", str(C.MASKFREE_DQN_MODEL_PATH), "baseline"),
    ("baseline mask-free PER", str(C.MASKFREE_PER_MODEL_PATH), "baseline"),
    ("coverage DQN", str(C.COVERAGE_DQN_MODEL_PATH), "coverage"),
    ("coverage PER", str(C.COVERAGE_PER_MODEL_PATH), "coverage"),
]

STATES = list(C.STATES)


def load_test(path, benign_cap: int = BENIGN_CAP, seed: int = SEED) -> pd.DataFrame:
    """All attack rows + a capped, seeded benign sample (stable FPR estimate)."""
    df = pd.read_parquet(path, columns=list(C.OBS_FEATURES) + list(C.HIDDEN_COLUMNS))
    benign = df[df["mdp_state"] == BENIGN]
    attack = df[df["mdp_state"] != BENIGN]
    if len(benign) > benign_cap:
        benign = benign.sample(n=benign_cap, random_state=seed)
    out = pd.concat([attack, benign], ignore_index=True)
    return out.sample(frac=1.0, random_state=seed).reset_index(drop=True)


def main() -> None:
    tests = {name: load_test(meta[0]) for name, meta in TESTS.items()}

    results: dict = {"_models": [m[0] for m in MODELS], "_groups": {m[0]: m[2] for m in MODELS}}
    for name, path, _ in MODELS:
        agent = DoubleDQNAgent.load(path)
        results[name] = {}
        for cond in CONDITIONS:
            results[name][cond] = {}
            for tname, df in tests.items():
                rng = np.random.default_rng(SEED)
                results[name][cond][tname] = evaluate(agent, df, cond, rng)

    # test-set composition + attack-label support
    meta = {}
    for tname, (path, bucket, label) in TESTS.items():
        df = tests[tname]
        comp = dict(df["mdp_state"].value_counts())
        meta[tname] = {
            "bucket": bucket, "label": label,
            "n": len(df),
            "composition": ", ".join(f"{k} {v:,}" for k, v in sorted(comp.items())),
            "attack_n": int((df["attack_label"] == label).sum()),
            "benign_n": int((df["mdp_state"] == BENIGN).sum()),
        }

    _write_report(results, meta)
    _write_confusion_png(results, tests)

    print(f"wrote {C.COVERAGE_ABLATION_REPORT_PATH}")
    print(f"wrote {C.COVERAGE_ABLATION_CM_PNG}")
    for name in results["_models"]:
        for tname in TESTS:
            rep = results[name]["corrupted"][tname]
            lab = TESTS[tname][2]
            v = rep["labels"].get(lab, {})
            print(f"  {name:24s} {tname:26s} corrupted "
                  f"recall({lab})={v.get('recall', float('nan')):.3f} "
                  f"f1={v.get('f1', float('nan')):.3f} "
                  f"benign_fpr={rep['benign_fpr']:.3f}")


def _attack_row(rep: dict, label: str) -> dict:
    return rep["labels"].get(label, {"precision": float("nan"),
                                     "recall": float("nan"), "f1": float("nan")})


def _write_report(results: dict, meta: dict) -> None:
    order = [m[0] for m in MODELS]
    lines: list[str] = []
    add = lines.append
    add("# Coverage ablation - does adding the missing concepts help?\n")
    add(f"`data/processed/{C.COVERAGE_ABLATION_REPORT_PATH.name}` - generated by "
        "`PYTHONPATH=src python -m rl_ids.coverage_eval`\n")

    add("## 1. Question\n")
    add("The mask-free agents fail on 2018 `Infilteration` (recall ~0.02) and only "
        "partially catch 2017 `PortScan` (recall ~0.41). The diagnosis "
        "(`dataset_preprocessing_report.md`, `coverage_split_report.md`) is missing "
        "**training coverage**: the train split contains **no PortScan** and only "
        "**36 Infiltration rows** (vs 137,720 in the 2018 holdout). This experiment "
        "adds the missing concepts and asks whether recall rises.\n")
    add("This is a **purely additive** test: `train.parquet` and the original "
        "holdouts are untouched, and the baseline agents (trained without coverage) "
        "are kept and scored on the *same* new test sets.\n")

    add("## 2. Method\n")
    add("- Training corpus = `train.parquet` (+) `coverage_train.parquet` "
        "(PortScan-day 80% + Wed-28 Infilteration), RNG-shuffled.")
    add("- Coverage agents retrained with the **same** network, episodes, seed and "
        "pool cap as the baseline mask-free agents; **only the data changed**.")
    add("- Baseline and coverage agents scored on identical unseen test sets, using "
        "the agent's own greedy action as the decision (no mask, no label leak).")
    add(f"- Q-values average {DRAWS} env-style observations under corrupted "
        "telemetry; also reported clean.")
    add(f"- Test benign traffic capped at {BENIGN_CAP:,} rows (FPR estimate); "
        "**all** attack rows kept.\n")

    add("## 3. Test sets\n")
    add("| Test set | Rows | Composition | Attack rows | Benign rows |")
    add("|---|---:|---|---:|---:|")
    for tname, m in meta.items():
        add(f"| {tname} | {m['n']:,} | {m['composition']} | {m['attack_n']:,} | "
            f"{m['benign_n']:,} |")
    add("")
    add("PortScan test is a **within-day temporal split** (last 20% of the PortScan "
        "day), so it shares a day with the PortScan training portion and is an "
        "optimistic bound; Infiltration test is a **separate day** (Thu-01 vs "
        "Wed-28) and is clean. Both remain unseen by every model.\n")

    add("## 4. Headline - attack-label recall (corrupted observations)\n")
    add("| Test set | Attack label | Model | Recall | Precision | F1 | Benign FPR |")
    add("|---|---|---|---:|---:|---:|---:|")
    for tname, m in meta.items():
        lab = m["label"]
        for name in order:
            rep = results[name]["corrupted"][tname]
            v = _attack_row(rep, lab)
            tag = "**" if results["_groups"][name] == "coverage" else ""
            add(f"| {tname.split(' ')[0]} | {lab} | {tag}{name}{tag} | "
                f"{v['recall']:.3f} | {v['precision']:.3f} | {v['f1']:.3f} | "
                f"{rep['benign_fpr']:.3f} |")
    add("")

    add("### Per-architecture delta (same net, seed, episodes - only the data changed)\n")
    add("| Test set | Attack label | Architecture | Baseline recall | Coverage recall | Δ recall | Baseline FPR | Coverage FPR |")
    add("|---|---|---|---:|---:|---:|---:|---:|")
    for tname, m in meta.items():
        lab = m["label"]
        for arch, base_name, cov_name in (
            ("DQN", "baseline mask-free DQN", "coverage DQN"),
            ("PER", "baseline mask-free PER", "coverage PER"),
        ):
            bv = _attack_row(results[base_name]["corrupted"][tname], lab)
            cv = _attack_row(results[cov_name]["corrupted"][tname], lab)
            b_fpr = results[base_name]["corrupted"][tname]["benign_fpr"]
            c_fpr = results[cov_name]["corrupted"][tname]["benign_fpr"]
            add(f"| {tname.split(' ')[0]} | {lab} | {arch} | {bv['recall']:.3f} | "
                f"{cv['recall']:.3f} | {cv['recall'] - bv['recall']:+.3f} | "
                f"{b_fpr:.3f} | {c_fpr:.3f} |")
    add("")

    add("### Clean observations (context)\n")
    add("| Test set | Attack label | Model | Recall | F1 | Benign FPR |")
    add("|---|---|---|---:|---:|---:|")
    for tname, m in meta.items():
        lab = m["label"]
        for name in order:
            rep = results[name]["clean"][tname]
            v = _attack_row(rep, lab)
            add(f"| {tname.split(' ')[0]} | {lab} | {name} | {v['recall']:.3f} | "
                f"{v['f1']:.3f} | {rep['benign_fpr']:.3f} |")
    add("")

    add(f"![Coverage ablation confusion matrices]({C.COVERAGE_ABLATION_CM_PNG.name})\n")
    add("*Figure: confusion matrices under corrupted observations (rows = true "
        "severity bucket, cols = predicted). Top two rows = baseline, bottom two = "
        "coverage.*\n")

    add("## 5. Bucket-level detail (corrupted)\n")
    for tname, m in meta.items():
        add(f"### {tname}\n")
        add(f"Bucket recall for the attack class **{m['bucket']}**, per model.\n")
        for name in order:
            rep = results[name]["corrupted"][tname]
            b = rep["buckets"][m["bucket"]]
            add(f"- **{name}** - {m['bucket']} recall {b['recall']:.3f}, precision "
                f"{b['precision']:.3f}, F1 {b['f1']:.3f}; macro F1 "
                f"{macro_average(rep['buckets'], 'f1'):.3f}; benign FPR "
                f"{rep['benign_fpr']:.3f}.")
        add("")

    add("## 6. Reading the result\n")
    arch_pairs = (("DQN", "baseline mask-free DQN", "coverage DQN"),
                  ("PER", "baseline mask-free PER", "coverage PER"))

    def delta(tname, lab, bn, cn):
        bv = _attack_row(results[bn]["corrupted"][tname], lab)
        cv = _attack_row(results[cn]["corrupted"][tname], lab)
        bf = results[bn]["corrupted"][tname]["benign_fpr"]
        cf = results[cn]["corrupted"][tname]["benign_fpr"]
        return bv["recall"], cv["recall"], cv["recall"] - bv["recall"], bf, cf

    for tname, m in meta.items():
        lab = m["label"]
        add(f"### {tname} - `{lab}`\n")
        for arch, bn, cn in arch_pairs:
            br, cr, dr, bf, cf = delta(tname, lab, bn, cn)
            add(f"- **{arch}**: recall {br:.3f} -> {cr:.3f} ({dr:+.3f}); "
                f"benign FPR {bf:.3f} -> {cf:.3f} ({cf - bf:+.3f}).")
        add("")

    ps_lab = meta["PortScan test (2017)"]["label"]
    inf_lab = meta["Infiltration test (2018)"]["label"]
    ps_dqn = delta("PortScan test (2017)", ps_lab, "baseline mask-free DQN", "coverage DQN")
    ps_per = delta("PortScan test (2017)", ps_lab, "baseline mask-free PER", "coverage PER")
    inf_dqn = delta("Infiltration test (2018)", inf_lab,
                    "baseline mask-free DQN", "coverage DQN")
    inf_per = delta("Infiltration test (2018)", inf_lab,
                    "baseline mask-free PER", "coverage PER")

    add("### What it means\n")
    add(f"- **PortScan: coverage is the fix.** With training coverage the recall "
        f"jumps in both architectures - DQN {ps_dqn[0]:.3f} -> {ps_dqn[1]:.3f} "
        f"({ps_dqn[2]:+.3f}), PER {ps_per[0]:.3f} -> {ps_per[1]:.3f} "
        f"({ps_per[2]:+.3f}) - on a family that had **zero** training rows before. "
        "The diagnosis (missing concept) is confirmed: for a truly absent family, "
        "adding it is what moves detection.")
    add(f"- **Read the FPR together with the recall.** The DQN's PortScan gain "
        f"costs a false-alarm rise ({ps_dqn[3]:.3f} -> {ps_dqn[4]:.3f}), while PER "
        f"buys a comparable recall jump at ~flat FPR ({ps_per[3]:.3f} -> "
        f"{ps_per[4]:.3f}). So *which agent consumes the new coverage* matters: PER "
        "turns it into recall without turning it into false alarms.")
    add(f"- **Infiltration: coverage helps less, and representation is why.** It "
        f"was added but stays a small share of the Compromised pool: DQN recall "
        f"{inf_dqn[0]:.3f} -> {inf_dqn[1]:.3f} ({inf_dqn[2]:+.3f}), PER "
        f"{inf_per[0]:.3f} -> {inf_per[1]:.3f} ({inf_per[2]:+.3f}). Existence was "
        "necessary but not sufficient - at natural proportion the concept is too "
        "diluted to dominate the DDoS/DoS mass, so the binding constraint has "
        "shifted from *coverage* to *representation*.")
    add("- **The original mask-free results remain the honest out-of-distribution "
        "baseline** (`maskfree_holdout_detection_report.md`); the coverage agents "
        "are the in-coverage counterpart and are only directly comparable on these "
        "test sets.\n")

    C.COVERAGE_ABLATION_REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")


def _write_confusion_png(results: dict, tests: dict) -> None:
    order = [m[0] for m in MODELS]
    holds = list(tests.keys())
    fig, axes = plt.subplots(len(order), len(holds),
                             figsize=(4.6 * len(holds), 3.9 * len(order)),
                             squeeze=False)
    for r, model in enumerate(order):
        for c, tname in enumerate(holds):
            ax = axes[r][c]
            cm = results[model]["corrupted"][tname]["cm"]
            ax.imshow(cm, cmap="Blues")
            for i in range(len(STATES)):
                for j in range(len(STATES)):
                    ax.text(j, i, f"{cm[i, j]}", ha="center", va="center",
                            color="black" if cm[i, j] < cm.max() * 0.6 else "white",
                            fontsize=9)
            ax.set_xticks(range(len(STATES)), STATES, rotation=30, ha="right")
            ax.set_yticks(range(len(STATES)), STATES)
            ax.set_xlabel("predicted")
            ax.set_ylabel("true")
            ax.set_title(f"{model}\n{tname.split(' ')[0]} (corrupted)", fontsize=10)
    fig.tight_layout()
    fig.savefig(C.COVERAGE_ABLATION_CM_PNG, dpi=110)
    plt.close(fig)


if __name__ == "__main__":
    main()
