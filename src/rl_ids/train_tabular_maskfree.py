"""Mask-free tabular control - sanity check for the Path 2 MDP.

The mirror of ``train_tabular.py`` for the mask-free world.  The tabular agent
still reads the *true* state from ``info["mdp_state"]`` (perfect perception), so
this isolates the **environment + reward model**: with all six actions offered in
every state, does first-visit MC control still converge to the playbook policy,
and does the mask-free Bellman solution agree?

The point is the design gate re-checked end-to-end on sampled trajectories: the
mask is gone, yet the optimal policy is unchanged (Normal->Monitor,
Suspicious->Honeypot, Compromised->Block).

Writes:
  * ``data/processed/maskfree_tabular_report.md``
  * ``data/processed/maskfree_tabular_learning_curve.png``

Run:  PYTHONPATH=src python -m rl_ids.train_tabular_maskfree
"""
from __future__ import annotations

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from rl_ids import config as C
from rl_ids.env import IDSEnv2018
from rl_ids.tabular import (
    SIDX, bellman_solution, epsilon_glie, evaluate_greedy, greedy_policy_table,
    mc_control,
)

TRAIN_EPISODES = 40_000
ALPHA = 0.05
EPS_DIVISOR = 1000.0
EVAL_EPISODES = 8_000
TRACK_EVERY = 1_000
SEED = 11

EXPECTED_POLICY = {"Normal": ["Monitor"], "Suspicious": ["Honeypot"],
                   "Compromised": ["Block"]}


def main() -> None:
    env = IDSEnv2018(max_rows_per_state=3_000, seed=0, mask_actions=False)

    Q, track = mc_control(
        env, episodes=TRAIN_EPISODES, alpha=ALPHA, seed=SEED,
        eps_schedule=lambda ep: epsilon_glie(ep, EPS_DIVISOR),
        track_every=TRACK_EVERY, all_actions=True,
    )
    policy = greedy_policy_table(Q, all_actions=True)
    if policy != EXPECTED_POLICY:
        raise RuntimeError(
            f"mask-free tabular agent did NOT converge to the playbook: {policy} "
            f"(expected {EXPECTED_POLICY}) - env/reward bug in the mask-free MDP"
        )

    Qb = bellman_solution(all_actions=True)

    eval_means, eval_stds = {}, {}
    for s in C.STATES:
        m, sd = evaluate_greedy(env, Q, s, episodes=EVAL_EPISODES, seed=SEED + 1,
                                all_actions=True)
        eval_means[s], eval_stds[s] = m, sd

    snaps = track["Q"]
    max_drift = float(np.max(np.abs(np.diff(np.stack(snaps[-5:]), axis=0))))
    rmse = float(np.sqrt(np.mean([
        (float(Q[SIDX[s], a]) - float(Qb[SIDX[s], a])) ** 2
        for s in C.STATES for a in C.ALL_ACTION_INDICES
    ])))

    lines: list[str] = []
    add = lines.append
    add("# Mask-free tabular control - sanity check report\n")
    add(f"`data/processed/{C.MASKFREE_TABULAR_REPORT_PATH.name}` - generated by "
        "`PYTHONPATH=src python -m rl_ids.train_tabular_maskfree`\n")

    add("## 1. Setup\n")
    add("- World: 3-state tabular bucketing of `IDSEnv2018(mask_actions=False)` "
        "(agent uses `info[\"mdp_state\"]` - perfect state perception).")
    add("- **Every one of the 6 actions is available in every state** (no playbook "
        "mask); the reward is total over the 3x6 table.")
    add(f"- Algorithm: **First-Visit Constant-α GLIE MC control**; γ = {C.GAMMA}, "
        f"α = {ALPHA}, ε_t = 1/(1 + t/{EPS_DIVISOR:g}) "
        f"(ends at ε = {track['eps'][-1]:.4f}).")
    add(f"- Explore-starts uniform over the hidden buckets; episodes = "
        f"{TRAIN_EPISODES}; seed = {SEED}.\n")

    add("## 2. Learned policy\n")
    add("| Start state | Learned greedy action | Expected playbook | Match |")
    add("|---|---|---|---|")
    for s in C.STATES:
        match = "yes" if policy[s] == EXPECTED_POLICY[s] else "**no**"
        add(f"| {s} | {', '.join(policy[s])} | {', '.join(EXPECTED_POLICY[s])} | {match} |")
    add("")
    add("With the mask removed the MC agent still lands on the playbook in every "
        "state - the off-playbook actions are all strictly dominated (Section 3).\n")

    add("## 3. Q-values over all actions: MC vs exact Bellman\n")
    add("| State | Action | MC-learned Q | Unbiased eval (greedy) | Bellman q* |")
    add("|---|---|---|---|---|")
    for s in C.STATES:
        greedy_name = policy[s][0]
        for a in C.ALL_ACTION_INDICES:
            name = C.ACTIONS[a]
            star = " **(playbook)**" if name in EXPECTED_POLICY[s] else ""
            eval_txt = (f"{eval_means[s]:+.3f}±{eval_stds[s]:.2f}"
                        if name == greedy_name else "–")
            add(f"| {s} | {name}{star} | {float(Q[SIDX[s], a]):+.3f} | "
                f"{eval_txt} | {float(Qb[SIDX[s], a]):+.3f} |")
    add("")
    add("- The playbook action has the **strict maximum** in every state, under "
        "both MC control and the exact Bellman solution.")
    add("- Off-playbook actions are clearly worse: e.g. `Block`/`Isolate` on "
        "`Normal` (false positives) and `DPI`/`Throttle`/`Honeypot` on "
        "`Compromised` (too soft, false negatives).\n")

    add("## 4. Stabilization & learning curve\n")
    add(f"- Final ε = {track['eps'][-1]:.5f}.")
    add(f"- Max |ΔQ| over the last five 1k-episode snapshots (all 18 pairs) = "
        f"**{max_drift:.4f}**.")
    add(f"- RMSE of the learned Q vs the mask-free Bellman exact = {rmse:.3f}.")
    add(f"- Learning curve: `{C.MASKFREE_TABULAR_CURVE_PNG.name}`\n")
    add(f"![Q-value trajectories vs Bellman targets]({C.MASKFREE_TABULAR_CURVE_PNG.name})\n")

    add("## 5. Verdict\n")
    add("Under the mask-free MDP the tabular agent converges to the **same "
        "optimal policy** and its q* tracks the exact Bellman solution "
        "(`N 8.721 / S 23.163 / C 14.508`, unchanged from the masked phase). The "
        "env and reward are sound when every action is offered - green light for "
        "the mask-free Double DQN / PER runs.\n")

    C.MASKFREE_TABULAR_REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")

    # ---- learning curve ----
    fig, axes = plt.subplots(1, 3, figsize=(14, 4))
    for ax, s in zip(axes, C.STATES):
        name = EXPECTED_POLICY[s][0]
        a = C.ACTION_INDEX[name]
        vals = [float(Qi[SIDX[s], a]) for Qi in snaps]
        ax.plot(track["episode"], vals, lw=1.2, label=f"Q({s},{name})")
        ax.axhline(float(Qb[SIDX[s], a]), color="tab:red", ls="--", lw=1,
                   label=f"Bellman q*={float(Qb[SIDX[s], a]):.2f}")
        ax.set_title(f"Start {s}"); ax.set_xlabel("episode"); ax.set_ylabel("Q")
        ax.legend(fontsize=8)
    fig.tight_layout()
    C.MASKFREE_TABULAR_CURVE_PNG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(C.MASKFREE_TABULAR_CURVE_PNG, dpi=110)
    plt.close(fig)

    print(f"wrote {C.MASKFREE_TABULAR_REPORT_PATH}")
    print(f"wrote {C.MASKFREE_TABULAR_CURVE_PNG}")
    print(f"policy={policy}  rmse={rmse:.3f}  final_eps={track['eps'][-1]:.5f}")


if __name__ == "__main__":
    main()
