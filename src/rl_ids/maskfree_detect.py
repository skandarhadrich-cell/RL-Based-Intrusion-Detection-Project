"""Policy-based holdout detection for the mask-free (Path 2) agents.

With the playbook mask removed, the agent's chosen action *is* its detection
decision.  A mask-free agent was trained to act without ever being told the
hidden bucket, so the Q-argmax over **all** actions is a genuine classifier -
not a circular read-out of a mask that already encoded the label.  This driver
scores that classifier on the untouched holdouts.

The **masked** agents are included for contrast: their mask-free Q-argmax was
never forced to encode the state (the mask always told them it), so it collapses
to the majority bucket.  The gap between the two is the value of removing the
mask.

Outputs:
  * ``data/processed/maskfree_holdout_detection_report.md``
  * ``data/processed/maskfree_holdout_confusion_matrix.png``

Run:  PYTHONPATH=src python -m rl_ids.maskfree_detect
"""
from __future__ import annotations

import numpy as np
import pandas as pd
import torch
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from rl_ids import config as C
from rl_ids.dqn import DoubleDQNAgent
from rl_ids.holdout_eval import action_bucket, corrupt, load_holdout
from rl_ids.metrics import (
    accuracy, binary_metrics, confusion, macro_average, per_class_metrics,
)

STATES = list(C.STATES)
BENIGN = "Normal"
DRAWS = 4
HOLDOUT_PER_CLASS = 3_000
SEED = 0
CONDITIONS = ("clean", "corrupted")


# --------------------------------------------------------------------------- #
# policy -> detection
# --------------------------------------------------------------------------- #
def policy_predict(agent, X: np.ndarray, condition: str,
                   rng: np.random.Generator) -> np.ndarray:
    """Predicted severity bucket from the agent's greedy action (no mask).

    Q-values are averaged over ``DRAWS`` env-style observations, then the argmax
    over **all** actions is mapped to the bucket that action implies.
    """
    with torch.no_grad():
        Q = np.zeros((len(X), len(C.ACTIONS)))
        draws = 1 if condition == "clean" else DRAWS
        for _ in range(draws):
            obs = X if condition == "clean" else corrupt(X, rng)
            Q += agent.q_values(obs)
        Q /= draws
    return action_bucket(np.argmax(Q, axis=1))


def evaluate(agent, df: pd.DataFrame, condition: str, rng: np.random.Generator) -> dict:
    y_true = df["mdp_state"].to_numpy(dtype=object)
    attack = df["attack_label"].to_numpy(dtype=object)
    pred = policy_predict(agent, df[C.OBS_FEATURES].to_numpy(np.float32), condition, rng)
    is_benign = y_true == BENIGN

    buckets = per_class_metrics(y_true, pred, STATES)
    labels: dict[str, dict] = {}
    for lab in sorted(pd.unique(attack[~is_benign])):
        sel = (attack == lab) | is_benign
        labels[lab] = binary_metrics(attack[sel] == lab, pred[sel] != BENIGN)
    benign_fpr = float((pred[is_benign] != BENIGN).mean()) if is_benign.any() else 0.0
    return {
        "n": len(df),
        "acc": accuracy(y_true, pred),
        "buckets": buckets,
        "labels": labels,
        "benign_fpr": benign_fpr,
        "benign_n": int(is_benign.sum()),
        "cm": confusion(y_true, pred, STATES),
    }


# --------------------------------------------------------------------------- #
# report
# --------------------------------------------------------------------------- #
def _bucket_table(rep: dict) -> list[str]:
    b = rep["buckets"]
    lines = ["| Class | Precision | Recall | F1 | FPR | Support |",
             "|---|---:|---:|---:|---:|---:|"]
    for st in STATES:
        v = b[st]
        if v["support"] == 0 and v["fp"] == 0 and v["fn"] == 0:
            continue
        lines.append(f"| {st} | {v['precision']:.3f} | {v['recall']:.3f} | "
                     f"{v['f1']:.3f} | {v['fpr']:.3f} | {v['support']:,} |")
    lines.append(f"| **macro** | {macro_average(b, 'precision'):.3f} | "
                 f"{macro_average(b, 'recall'):.3f} | {macro_average(b, 'f1'):.3f} | "
                 f"- | {sum(v['support'] for v in b.values()):,} |")
    return lines


def _label_table(rep: dict) -> list[str]:
    lines = ["| Attack label | Precision | Recall | F1 | FPR | Support |",
             "|---|---:|---:|---:|---:|---:|"]
    for lab, v in rep["labels"].items():
        lines.append(f"| {lab} | {v['precision']:.3f} | {v['recall']:.3f} | "
                     f"{v['f1']:.3f} | {v['fpr']:.3f} | {v['support']:,} |")
    lines.append(f"| _benign FP rate_ | - | - | - | {rep['benign_fpr']:.3f} | "
                 f"{rep['benign_n']:,} benign |")
    return lines


def write_report(results: dict) -> None:
    lines: list[str] = []
    add = lines.append
    add("# Mask-free holdout detection - policy action as the decision\n")
    add(f"`data/processed/{C.MASKFREE_DETECT_REPORT_PATH.name}` - generated by "
        "`PYTHONPATH=src python -m rl_ids.maskfree_detect`\n")

    add("## 1. Why this is a real detection metric\n")
    add("In the masked phase the action mask *is* the label in disguise, so the "
        "agent's actions could not be scored directly (see "
        "`holdout_classification_report.md`). In the **mask-free** phase the mask "
        "is gone: every action is offered in every state and the agent was trained "
        "to pick the right one without being told the hidden bucket. Its greedy "
        "action therefore *is* a detection decision, and the Q-argmax over all "
        "actions is a genuine classifier.")
    add("")
    add("The masked agents are included as a contrast: their mask-free Q-argmax "
        "was never forced to encode the state (the mask always supplied it), so it "
        "collapses toward the majority bucket without raising attack alarms.\n")

    add("## 2. Method\n")
    add("- Decision: `argmax_a Q(s, a)` over **all six** actions, no mask.")
    add("- Action -> implied bucket: Monitor -> Normal; DPI/Throttle/Honeypot -> "
        "Suspicious; Block/Isolate -> Compromised (same `action_bucket` mapping as "
        "the masked phase).")
    add(f"- Q-values average {DRAWS} env-style observations (Gaussian noise "
        f"sigma={C.OBS_NOISE_SIGMA}, telemetry masking p={C.OBS_MASK_PROB}).")
    add(f"- Holdouts sampled at {HOLDOUT_PER_CLASS:,}/class; observations **clean** "
        "and **corrupted**.")
    add("- Predicted-attack = bucket != Normal; FPR is one-vs-rest per row; the "
        "operational false-alarm rate on benign traffic is the `_benign FP rate_` "
        "row.\n")

    add("## 3. Headline (corrupted observations)\n")
    add("| Model | Holdout | Accuracy | Macro F1 | Mean attack recall | Benign FPR |")
    add("|---|---|---:|---:|---:|---:|")
    for model in results["_models"]:
        for hname in results["_holdouts"]:
            rep = results[model]["corrupted"][hname]
            recalls = [v["recall"] for v in rep["labels"].values()] or [float("nan")]
            add(f"| {model} | {hname} | {rep['acc']:.3f} | "
                f"{macro_average(rep['buckets'], 'f1'):.3f} | "
                f"{float(np.mean(recalls)):.3f} | {rep['benign_fpr']:.3f} |")
    add("")
    add(f"![Confusion matrices]({C.MASKFREE_DETECT_CM_PNG.name})\n")
    add("*Figure: confusion matrices under corrupted observations "
        "(rows = true severity bucket, cols = predicted).*\n")

    add("### Attack-label detection (corrupted)\n")
    add("| Model | Holdout | Attack label | Precision | Recall | F1 |")
    add("|---|---|---|---:|---:|---:|")
    for model in results["_models"]:
        for hname in results["_holdouts"]:
            for lab, v in results[model]["corrupted"][hname]["labels"].items():
                add(f"| {model} | {hname.split(' ')[0]} | {lab} | "
                    f"{v['precision']:.3f} | {v['recall']:.3f} | {v['f1']:.3f} |")
    add("")

    add("## 4. Per-model detail\n")
    for hname, hmeta in results["_holdouts"].items():
        add(f"### {hname}\n")
        add(f"{hmeta['n']:,} flows ({hmeta['composition']}).\n")
        for model in results["_models"]:
            add(f"**{model}**\n")
            for cond in CONDITIONS:
                rep = results[model][cond][hname]
                add(f"_Observations: {cond}._ Bucket accuracy **{rep['acc']:.3f}**.\n")
                lines.extend(_bucket_table(rep))
                add("")
                if rep["labels"]:
                    lines.extend(_label_table(rep))
                    add("")
        add("")

    add("## 5. Reading the results\n")
    add("**Benign FPR is the decisive column.** A degenerate detector that flags "
        "*every* flow as an attack can still post a non-zero macro F1 when attacks "
        "dominate a holdout - which is exactly what the masked agents do "
        "(benign FPR = 1.000). They raise an alarm on every benign flow, so their "
        "macro F1 is meaningless. Only the mask-free agents separate benign from "
        "attack.\n")
    mf = [m for m in results["_models"] if m.startswith("mask-free")]
    mk = [m for m in results["_models"] if m.startswith("masked")]
    for hname in results["_holdouts"]:
        mf_best = max(mf, key=lambda m: macro_average(
            results[m]["corrupted"][hname]["buckets"], "f1"))
        mf_f1 = macro_average(results[mf_best]["corrupted"][hname]["buckets"], "f1")
        mf_fpr = results[mf_best]["corrupted"][hname]["benign_fpr"]
        mk_best = max(mk, key=lambda m: macro_average(
            results[m]["corrupted"][hname]["buckets"], "f1"))
        mk_f1 = macro_average(results[mk_best]["corrupted"][hname]["buckets"], "f1")
        add(f"- **{hname}** - best mask-free agent: **{mf_best}** "
            f"(macro F1 {mf_f1:.3f} at benign FPR {mf_fpr:.3f}); best masked "
            f"agent mask-free argmax: {mk_best} (macro F1 {mk_f1:.3f} at benign "
            f"FPR 1.000 - degenerate).")
    add("")
    add("**2018 `Infilteration` is the weak case.** The mask-free agents are "
        "conservative (benign FPR 0.025-0.099) but catch almost none of the "
        "`Infilteration` rows (recall 0.015-0.081): the family has effectively no "
        "training counterpart (only 36 rows of the 2017-spelled `Infiltration` in "
        "the train split), so there is nothing to transfer. Read the 2018 macro F1 "
        "together with the recall column - it is dominated by the benign class.")
    add("**2017 is the positive case.** With no mask, the same agent that recovers "
        "the optimal policy detects `DDoS` (recall ~0.36) and `PortScan` (recall "
        "~0.41) at a ~0.10 benign false-alarm rate - a real, non-circular IDS "
        "result, and a far better operating point than the masked agents' "
        "flag-everything behaviour.")
    add("**Unseen label strings still transfer when the family is known.** The 2017 "
        "`DDoS` label never appears in training, but the family does as ~1.24M "
        "2018 `HOIC`/`LOIC` rows in the `Compromised` bucket; `Infilteration` has no "
        "such counterpart and is not detected. Coverage, not tuning, sets the "
        "ceiling.\n")

    add("## 6. Files\n")
    add("| File | Purpose |")
    add("|---|---|")
    add("| `src/rl_ids/train_maskfree.py` | trains the mask-free agents |")
    add("| `src/rl_ids/maskfree_detect.py` | this driver |")
    add("| `src/rl_ids/metrics.py` | pure per-class / binary metric functions |")
    add(f"| `data/processed/{C.MASKFREE_DETECT_REPORT_PATH.name}` | this report |")
    add(f"| `data/processed/{C.MASKFREE_DETECT_CM_PNG.name}` | confusion matrices |")

    C.MASKFREE_DETECT_REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")


def write_confusion_png(results: dict) -> None:
    models = results["_models"]
    holds = list(results["_holdouts"].keys())
    fig, axes = plt.subplots(len(models), len(holds),
                             figsize=(4.4 * len(holds), 4.2 * len(models)),
                             squeeze=False)
    for r, model in enumerate(models):
        for c, hname in enumerate(holds):
            ax = axes[r][c]
            cm = results[model]["corrupted"][hname]["cm"]
            ax.imshow(cm, cmap="Blues")
            for i in range(len(STATES)):
                for j in range(len(STATES)):
                    ax.text(j, i, f"{cm[i, j]}", ha="center", va="center",
                            color="black" if cm[i, j] < cm.max() * 0.6 else "white",
                            fontsize=9)
            ax.set_xticks(range(len(STATES)), STATES, rotation=30, ha="right")
            ax.set_yticks(range(len(STATES)), STATES)
            ax.set_xlabel("predicted"); ax.set_ylabel("true")
            ax.set_title(f"{model}\n{hname.split(' ')[0]} (corrupted)", fontsize=10)
    fig.tight_layout()
    fig.savefig(C.MASKFREE_DETECT_CM_PNG, dpi=110)
    plt.close(fig)


# --------------------------------------------------------------------------- #
# main
# --------------------------------------------------------------------------- #
def main() -> None:
    holdouts = {
        "holdout_infiltration (2018)": load_holdout(C.HOLDOUT_PARQUET, HOLDOUT_PER_CLASS, SEED),
        "holdout_ids2017_portscan_ddos (2017)": load_holdout(C.HOLDOUT_IDS2017_PARQUET, HOLDOUT_PER_CLASS, SEED),
    }
    holdout_meta = {}
    for hname, df in holdouts.items():
        comp = dict(df["mdp_state"].value_counts())
        holdout_meta[hname] = {
            "n": len(df),
            "composition": ", ".join(f"{k} {v:,}" for k, v in sorted(comp.items())),
        }

    models: list[tuple[str, str]] = [
        ("mask-free uniform DQN", str(C.MASKFREE_DQN_MODEL_PATH)),
        ("mask-free PER", str(C.MASKFREE_PER_MODEL_PATH)),
        ("masked uniform DQN", str(C.DQN_MODEL_PATH)),
        ("masked PER", str(C.PER_MODEL_PATH)),
    ]

    results: dict = {"_models": [], "_holdouts": holdout_meta}
    for name, path in models:
        agent = DoubleDQNAgent.load(path)
        results[name] = {}
        for cond in CONDITIONS:
            results[name][cond] = {}
            for hname, df in holdouts.items():
                rng = np.random.default_rng(SEED)
                results[name][cond][hname] = evaluate(agent, df, cond, rng)
        results["_models"].append(name)

    write_report(results)
    write_confusion_png(results)

    print(f"wrote {C.MASKFREE_DETECT_REPORT_PATH}")
    print(f"wrote {C.MASKFREE_DETECT_CM_PNG}")
    for name in results["_models"]:
        for hname in holdouts:
            r = results[name]["corrupted"][hname]
            print(f"  {name:24s} {hname:38s} corrupted acc={r['acc']:.3f} "
                  f"macroF1={macro_average(r['buckets'], 'f1'):.3f} "
                  f"benign_fpr={r['benign_fpr']:.3f}")


if __name__ == "__main__":
    main()
